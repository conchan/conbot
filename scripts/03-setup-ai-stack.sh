#!/usr/bin/env bash
# =============================================================================
# 03-setup-ai-stack.sh
# Run this INSIDE the Ubuntu 24.04 LXC container (CT 101 / ai-stack).
# Access the container shell via: Proxmox UI → CT 101 → Shell
#
# What it does:
#   - Updates the system
#   - Installs Docker + Docker Compose plugin
#   - Creates ~/ai-stack/docker-compose.yml
#   - Starts Ollama + Open WebUI containers
#   - Pulls both models: qwen3:4b (voice) and qwen3:14b (chat/MCP)
# =============================================================================
set -euo pipefail

RED='\033[0;31m'; GREEN='\033[0;32m'; YELLOW='\033[1;33m'; CYAN='\033[0;36m'; NC='\033[0m'
info()    { echo -e "${GREEN}[INFO]${NC}  $*"; }
warn()    { echo -e "${YELLOW}[WARN]${NC}  $*"; }
error()   { echo -e "${RED}[ERROR]${NC} $*"; exit 1; }
section() { echo -e "\n${CYAN}══════════════════════════════════════${NC}"; echo -e "${CYAN}  $*${NC}"; echo -e "${CYAN}══════════════════════════════════════${NC}"; }

[[ $EUID -ne 0 ]] && error "Run as root inside the LXC container shell."

# --- Configurable variables --------------------------------------------------
AI_STACK_DIR="${HOME}/ai-stack"
OLLAMA_PORT=11434
WEBUI_PORT=3000

# Both models are pulled so they sit in memory simultaneously.
#   qwen3:4b  → HA voice pipeline (fast response, handles device commands perfectly)
#   qwen3:14b → Open WebUI chat + MCP agent workflows (higher quality for deliberate tasks)
# Both fit comfortably within the 48 GB RAM allocation with headroom to spare.
MODELS_TO_PULL=(
  "qwen3:4b"    # ~2.6 GB — voice assistant model
  "qwen3:14b"   # ~8.2 GB — chat / MCP agent model
)

# =============================================================================
section "Step 1: System Update"
# =============================================================================
info "Updating package lists and upgrading system..."
apt-get update -q
DEBIAN_FRONTEND=noninteractive apt-get upgrade -y -q

info "Installing prerequisites..."
DEBIAN_FRONTEND=noninteractive apt-get install -y -q \
  curl ca-certificates gnupg lsb-release htop net-tools jq

# =============================================================================
section "Step 2: Install Docker"
# =============================================================================
if command -v docker &>/dev/null; then
  info "Docker already installed ($(docker --version)) — skipping."
else
  info "Adding Docker's official GPG key..."
  install -m 0755 -d /etc/apt/keyrings
  curl -fsSL https://download.docker.com/linux/ubuntu/gpg \
    -o /etc/apt/keyrings/docker.asc
  chmod a+r /etc/apt/keyrings/docker.asc

  info "Adding Docker repository..."
  echo \
    "deb [arch=$(dpkg --print-architecture) signed-by=/etc/apt/keyrings/docker.asc] \
    https://download.docker.com/linux/ubuntu $(lsb_release -cs) stable" \
    > /etc/apt/sources.list.d/docker.list

  apt-get update -q
  info "Installing Docker Engine..."
  DEBIAN_FRONTEND=noninteractive apt-get install -y -q \
    docker-ce docker-ce-cli containerd.io docker-buildx-plugin docker-compose-plugin

  systemctl enable --now docker
  info "Docker installed: $(docker --version)"
fi

# Verify compose plugin
docker compose version &>/dev/null || error "Docker Compose plugin not found. Check Docker installation."

# =============================================================================
section "Step 3: Create Docker Compose Stack"
# =============================================================================
info "Creating AI stack directory at $AI_STACK_DIR..."
mkdir -p "$AI_STACK_DIR"

COMPOSE_FILE="$AI_STACK_DIR/docker-compose.yml"

if [[ -f "$COMPOSE_FILE" ]]; then
  warn "docker-compose.yml already exists — backing up to docker-compose.yml.bak"
  cp "$COMPOSE_FILE" "${COMPOSE_FILE}.bak"
fi

info "Writing docker-compose.yml..."
cat > "$COMPOSE_FILE" << EOF
# Ollama + Open WebUI — AI inference stack
# Generated by 03-setup-ai-stack.sh
# Docs: https://github.com/ollama/ollama  |  https://github.com/open-webui/open-webui

services:
  ollama:
    image: ollama/ollama:latest
    container_name: ollama
    restart: always
    ports:
      - "${OLLAMA_PORT}:11434"
    volumes:
      - ollama_data:/root/.ollama
    # Uncomment the block below to experiment with AMD GPU acceleration (gfx1150 workaround).
    # Results vary — check https://github.com/ollama/ollama/issues/9999 for current status.
    # environment:
    #   - HSA_OVERRIDE_GFX_VERSION=11.0.0
    # devices:
    #   - /dev/kfd
    #   - /dev/dri

  open-webui:
    image: ghcr.io/open-webui/open-webui:main
    container_name: open-webui
    restart: always
    ports:
      - "${WEBUI_PORT}:8080"
    environment:
      - OLLAMA_BASE_URL=http://ollama:11434
      - DEFAULT_MODELS=qwen3:14b
    volumes:
      - open_webui_data:/app/backend/data
    depends_on:
      - ollama

volumes:
  ollama_data:
  open_webui_data:
EOF

info "docker-compose.yml written."

# =============================================================================
section "Step 4: Start the Stack"
# =============================================================================
info "Pulling images and starting containers (may take a few minutes)..."
cd "$AI_STACK_DIR"
docker compose pull
docker compose up -d

info "Waiting 10 seconds for containers to initialize..."
sleep 10

# Basic health check
OLLAMA_UP=$(docker inspect -f '{{.State.Running}}' ollama 2>/dev/null || echo "false")
WEBUI_UP=$(docker inspect -f '{{.State.Running}}' open-webui 2>/dev/null || echo "false")

[[ "$OLLAMA_UP" == "true" ]] && info "Ollama: running ✓" || warn "Ollama: not running — check 'docker compose logs ollama'"
[[ "$WEBUI_UP" == "true" ]] && info "Open WebUI: running ✓" || warn "Open WebUI: not running — check 'docker compose logs open-webui'"

# =============================================================================
section "Step 5: Pull AI Models"
# =============================================================================
info "Pulling AI models. This will take time depending on your internet speed..."
for MODEL in "${MODELS_TO_PULL[@]}"; do
  info "Pulling $MODEL ..."
  docker exec ollama ollama pull "$MODEL" && info "$MODEL pulled ✓" || warn "Failed to pull $MODEL — retry with: docker exec ollama ollama pull $MODEL"
done

# =============================================================================
section "Setup Complete"
# =============================================================================
HOST_IP=$(hostname -I | awk '{print $1}')
echo ""
echo -e "${GREEN}AI stack is running!${NC}"
echo ""
echo "  Open WebUI:   http://${HOST_IP}:${WEBUI_PORT}"
echo "  Ollama API:   http://${HOST_IP}:${OLLAMA_PORT}"
echo ""
echo "Next steps:"
echo "  1. Open Open WebUI in your browser and create your admin account"
echo "  2. Disable new sign-ups: Open WebUI → Settings → Disable 'Enable New Sign Ups'"
echo "  3. In Home Assistant → Settings → Integrations → Add → Ollama"
echo "     URL: http://${HOST_IP}:${OLLAMA_PORT}"
echo "  4. Assign a static DHCP lease for this container in your router"
echo "     (current IP: ${HOST_IP})"
echo ""
echo "Manage the stack:"
echo "  cd $AI_STACK_DIR"
echo "  docker compose ps          # status"
echo "  docker compose logs -f     # live logs"
echo "  docker compose pull && docker compose up -d   # update images"
echo ""
